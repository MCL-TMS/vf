/**
 * VF物流时效数据表创建脚本
 * 
 * 用途: 创建TSK_TIMELINESS_DATA表，用于存储用户上传的时效标准数据
 * 执行方式: 在Oracle SQL Developer或命令行中执行此SQL
 * 
 * 使用场景: Plan vs Actual时效对比分析
 */

-- 1. 检查表是否已存在
SELECT COUNT(*) as TABLE_EXISTS
FROM ALL_TABLES
WHERE OWNER = 'APP_CMS' AND TABLE_NAME = 'TSK_TIMELINESS_DATA';

-- 2. 如果表不存在，创建表
-- 注意：如果表已存在，会报错ORA-00955，可以忽略
CREATE TABLE APP_CMS.TSK_TIMELINESS_DATA (
    -- 主键
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    
    -- 业务字段
    BRAND_CODE VARCHAR2(50) NOT NULL,          -- 品牌代码（如：18405、18405-1等）
    BRAND_NAME VARCHAR2(100),                  -- 品牌名称（如：DICKIES、TNF等）
    CITY_NAME VARCHAR2(200) NOT NULL,          -- 城市名称
    AREA_ID VARCHAR2(50),                      -- 区域ID（对应BAS_AREA.AREA_ID）
    CARRIER_NAME VARCHAR2(100) NOT NULL,       -- 快递商名称（对应TSK_LIST_TASK.CARRIERID）
    TIME_VALUE NUMBER(10, 2) NOT NULL,         -- 时效值（单位：小时）
    TIME_UNIT VARCHAR2(20) DEFAULT 'HOUR',     -- 时间单位（HOUR/DAY）
    
    -- 上传批次信息
    BATCH_ID VARCHAR2(100),                    -- 批次ID
    UPLOAD_TIME DATE DEFAULT SYSDATE,          -- 上传时间
    UPLOAD_USER VARCHAR2(100),                 -- 上传用户
    FILE_NAME VARCHAR2(500),                   -- 原始文件名
    
    -- 元数据
    REMARKS VARCHAR2(500),                     -- 备注
    IS_ACTIVE CHAR(1) DEFAULT 'Y',             -- 是否有效（Y/N）
    CREATED_TIME DATE DEFAULT SYSDATE,         -- 创建时间
    UPDATED_TIME DATE DEFAULT SYSDATE          -- 更新时间
);

-- 3. 创建索引（提升查询性能）
CREATE INDEX IDX_TIMELINESS_BRAND ON APP_CMS.TSK_TIMELINESS_DATA(BRAND_CODE);
CREATE INDEX IDX_TIMELINESS_CITY ON APP_CMS.TSK_TIMELINESS_DATA(CITY_NAME);
CREATE INDEX IDX_TIMELINESS_CARRIER ON APP_CMS.TSK_TIMELINESS_DATA(CARRIER_NAME);
CREATE INDEX IDX_TIMELINESS_AREA ON APP_CMS.TSK_TIMELINESS_DATA(AREA_ID);
CREATE INDEX IDX_TIMELINESS_BATCH ON APP_CMS.TSK_TIMELINESS_DATA(BATCH_ID);

-- 4. 创建复合索引（优化JOIN查询）
CREATE INDEX IDX_TIMELINESS_COMPOSITE ON APP_CMS.TSK_TIMELINESS_DATA(
    BRAND_CODE, 
    CARRIER_NAME, 
    CITY_NAME
);

-- 5. 添加注释
COMMENT ON TABLE APP_CMS.TSK_TIMELINESS_DATA IS '时效标准数据表 - 存储用户上传的Plan时效目标';
COMMENT ON COLUMN APP_CMS.TSK_TIMELINESS_DATA.ID IS '主键ID（自增）';
COMMENT ON COLUMN APP_CMS.TSK_TIMELINESS_DATA.BRAND_CODE IS '品牌代码（18405=DICKIES, 18405-1=TNF, 18405-2=ICEBREAKER, 18405-3=VANS, 18405-4=TIMBERLAND）';
COMMENT ON COLUMN APP_CMS.TSK_TIMELINESS_DATA.BRAND_NAME IS '品牌名称';
COMMENT ON COLUMN APP_CMS.TSK_TIMELINESS_DATA.CITY_NAME IS '城市名称（用于匹配BAS_AREA.AREA_NAME）';
COMMENT ON COLUMN APP_CMS.TSK_TIMELINESS_DATA.AREA_ID IS '区域ID（用于匹配BAS_AREA.AREA_ID）';
COMMENT ON COLUMN APP_CMS.TSK_TIMELINESS_DATA.CARRIER_NAME IS '快递商名称（用于匹配TSK_LIST_TASK.CARRIERID）';
COMMENT ON COLUMN APP_CMS.TSK_TIMELINESS_DATA.TIME_VALUE IS 'Plan时效值（单位：小时）';
COMMENT ON COLUMN APP_CMS.TSK_TIMELINESS_DATA.BATCH_ID IS '上传批次ID';
COMMENT ON COLUMN APP_CMS.TSK_TIMELINESS_DATA.IS_ACTIVE IS '是否有效（Y=有效, N=无效）';

